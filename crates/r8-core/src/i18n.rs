//! UI language support. English is the default.

use serde::{Deserialize, Serialize};

use crate::actions::Action;

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize, Default)]
#[serde(rename_all = "snake_case")]
pub enum Lang {
    #[default]
    En,
    Da,
    De,
    Sv,
    No,
}

impl Lang {
    pub const ALL: [Lang; 5] = [Lang::En, Lang::Da, Lang::De, Lang::Sv, Lang::No];

    pub fn code(self) -> &'static str {
        match self {
            Lang::En => "en",
            Lang::Da => "da",
            Lang::De => "de",
            Lang::Sv => "sv",
            Lang::No => "no",
        }
    }

    /// Native name shown in the language picker.
    pub fn native_name(self) -> &'static str {
        match self {
            Lang::En => "English",
            Lang::Da => "Dansk",
            Lang::De => "Deutsch",
            Lang::Sv => "Svenska",
            Lang::No => "Norsk",
        }
    }
}

pub fn stage_color_name(lang: Lang, index: usize) -> &'static str {
    const EN: [&str; 6] = ["Yellow", "Green", "Orange", "Pink", "Blue", "Purple"];
    const DA: [&str; 6] = ["Gul", "Grøn", "Orange", "Pink", "Blå", "Lilla"];
    const DE: [&str; 6] = ["Gelb", "Grün", "Orange", "Pink", "Blau", "Lila"];
    const SV: [&str; 6] = ["Gul", "Grön", "Orange", "Rosa", "Blå", "Lila"];
    const NO: [&str; 6] = ["Gul", "Grønn", "Oransje", "Rosa", "Blå", "Lilla"];
    let table = match lang {
        Lang::En => &EN,
        Lang::Da => &DA,
        Lang::De => &DE,
        Lang::Sv => &SV,
        Lang::No => &NO,
    };
    table.get(index).copied().unwrap_or("?")
}

